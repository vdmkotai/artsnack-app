/**
 * Rebuilds lib/higgsfield-prices.ts from Higgsfield's own quotes.
 *
 * See scripts/higgsfield-prices.md for when and why. Requires the official CLI
 * on PATH and an authenticated account; `generate cost` creates no job and
 * spends nothing.
 */

import { execFile } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { promisify } from "node:util";

import { API_MODELS, videoResolutions, type ApiModelId } from "../packages/shared/api-models";
import { buildHiggsfieldJob, costSignature } from "../packages/shared/higgsfield-job";

const run = promisify(execFile);

const OUTPUT = new URL("../lib/higgsfield-prices.ts", import.meta.url).pathname;

type Probe = { signature: string; args: string[] };

/** Every configuration the form can reach, as a CLI invocation. */
function probes(): Probe[] {
  const found = new Map<string, Probe>();

  const add = (signature: string, args: string[]) => {
    if (!found.has(signature)) found.set(signature, { signature, args });
  };

  for (const id of Object.keys(API_MODELS) as ApiModelId[]) {
    const model = API_MODELS[id];
    if (model.provider !== "higgsfield") continue;

    const image = model.image;
    if (image.kind === "higgsfield-image") {
      for (const tier of image.sizeTiers) {
        const request = buildHiggsfieldJob({
          model: id,
          mediaType: "image",
          prompt: "probe",
          sizeTier: tier.value,
          aspectRatio: image.aspectRatios[0],
        });
        add(costSignature(request), [
          image.jobType,
          "--prompt",
          "probe",
          `--${image.sizeParam}`,
          tier.value,
        ]);
      }
    }

    const caps = model.video;
    if (caps.kind !== "higgsfield-video") continue;
    for (const video of caps.models) {
      // Audio is a priced dimension on Kling — 10 credits with sound at 5s
      // against 7.5 without — so both states need their own entry.
      const audioStates = video.audioParam ? [true, false] : [undefined];
      for (const generateAudio of audioStates) {
        for (const mode of video.modeParam?.values ?? [undefined]) {
          const resolutions = videoResolutions(caps, undefined, video.jobType, mode);
          for (const duration of video.durations) {
            for (const resolution of resolutions.length > 0 ? resolutions : [undefined]) {
              const request = buildHiggsfieldJob({
                model: id,
                mediaType: "video",
                prompt: "probe",
                videoJobType: video.jobType,
                mode,
                generateAudio,
                durationSeconds: duration,
                resolution,
                aspectRatio: video.aspectRatios[0],
              });
              const args = [video.jobType, "--prompt", "probe", "--duration", String(duration)];
              if (resolution) args.push("--resolution", resolution);
              if (mode) args.push("--mode", mode);
              if (generateAudio !== undefined && video.audioParam) {
                args.push(
                  `--${video.audioParam.name}`,
                  video.audioParam.kind === "boolean"
                    ? String(generateAudio)
                    : generateAudio
                      ? "on"
                      : "off",
                );
              }
              add(costSignature(request), args);
            }
          }
        }
      }
    }
  }

  return [...found.values()];
}

async function quote(probe: Probe): Promise<number | null> {
  try {
    const { stdout, stderr } = await run("higgsfield", ["generate", "cost", ...probe.args]);
    const match = /([0-9]+(?:\.[0-9]+)?)\s*credits/.exec(`${stdout}${stderr}`);
    return match ? Number(match[1]) : null;
  } catch {
    // The vendor refuses combinations the UI never offers (Seedance fast above
    // 720p). Reported below rather than swallowed, so a genuine breakage is
    // still visible.
    return null;
  }
}

async function main() {
  const list = probes();
  const prices = new Map<string, number>();
  const refused: string[] = [];

  for (const [index, probe] of list.entries()) {
    const credits = await quote(probe);
    if (credits === null) refused.push(probe.signature);
    else prices.set(probe.signature, credits);
    if (index % 25 === 0) console.error(`  ${index}/${list.length}`);
  }

  const today = new Date().toISOString().slice(0, 10);
  const { stdout: version } = await run("higgsfield", ["--version"]).catch(() => ({
    stdout: "unknown",
  }));

  const body = [...prices.keys()]
    .sort()
    .map((key) => `  "${key}": ${prices.get(key)},`)
    .join("\n");

  await writeFile(
    OUTPUT,
    `/**
 * Higgsfield's published rates, as quoted by their own CLI.
 *
 * Generated by scripts/higgsfield-prices.ts — do not edit by hand. Higgsfield
 * publishes no rate card, so every figure here came from
 * \`higgsfield generate cost\` against the live account.
 *
 * This is a floor, not the truth: a live quote for the same configuration
 * always wins, and the real charge is written back when a job finishes. It
 * exists so the Generate button shows a real number on the first paint instead
 * of an ellipsis that resolves a round trip later.
 *
 * Keyed by {@link costSignature}, which deliberately omits aspect ratio and
 * reference count: both were measured against the vendor and neither moves the
 * price, so folding them in would multiply this table for nothing.
 *
 * Captured ${today} against CLI ${version.trim().split(" ")[1] ?? "unknown"}.
 */
export const HIGGSFIELD_LIST_PRICE: Readonly<Record<string, number>> = {
${body}
};
`,
  );

  console.error(`priced ${prices.size}/${list.length}`);
  for (const signature of refused) console.error(`  refused by vendor: ${signature}`);
}

void main();
